/** Keep static workbench tutorial data and self-contained offline exports aligned. */
import fs from 'node:fs';
import { getTutorialPlacement, watchTutorialPosition } from '../../src/tutorial/placement.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { inlineTutorialAssets } from '../../global-evidence-workbench/ui/scripts/inline-tutorial.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ui = path.join(root, 'global-evidence-workbench/ui');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'src/tutorial/catalog.json'), 'utf8'));
const content = `// Generated by scripts/tutorial/sync-static.mjs; edit src/tutorial/catalog.json or placement.mjs.\nexport const tutorialContent = ${JSON.stringify({version:catalog.version,staticGuides:catalog.staticGuides,caseStudy:catalog.caseStudy}).replaceAll('<','\\u003c')};\ntutorialContent.getPlacement = ${getTutorialPlacement.toString()};\ntutorialContent.watchPosition = ${watchTutorialPosition.toString()};\n`;
const target = path.join(ui, 'src/tutorial-content.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw Error('Static tutorial content is stale. Run node scripts/tutorial/sync-static.mjs.');
  console.log('Static tutorial content is in sync.');
} else {
  fs.writeFileSync(target, content);
  console.log('Prepared static tutorial content.');
}
if (process.argv.includes('--inline-dist')) {
  for (const filename of ['fieldwork-offline.html', 'finance-offline.html', 'media-offline.html']) {
    const file = path.join(ui, 'dist', filename);
    if (!fs.existsSync(file)) throw Error(`Build standalone exports before tutorial inlining: ${file}`);
    const html = inlineTutorialAssets(fs.readFileSync(file, 'utf8'));
    fs.writeFileSync(file, html);
  }
  console.log('Inlined tutorial assets in all three standalone exports.');
}
